// SCIENTIFIC MULTI-LEVEL DIAGNOSTIC GENERATOR:
// To prevent guessing, it picks 2-3 random questions from EVERY CEFR level (A1 -> A2 -> B1 -> B2 -> C1)
// Total 10-15 questions covering all 5 stages!
export function getComprehensiveDiagnosticQuiz(questionsPerLevel: number = 2): DiagnosticQuestion[] {
  const levels: CEFRLevel[] = ['A1', 'A2', 'B1', 'B2', 'C1'];
  const fullQuiz: DiagnosticQuestion[] = [];

  levels.forEach(lvl => {
    const levelPool = QUESTION_POOL.filter(q => q.level === lvl);
    const shuffled = [...levelPool].sort(() => 0.5 - Math.random());
    const selected = shuffled.slice(0, questionsPerLevel);
    fullQuiz.push(...selected);
  });

  return fullQuiz;
}
